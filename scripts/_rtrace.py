# -*- coding: utf-8 -*-
"""Trace recent R-version code outputs and where they landed. Read-only.
Run: py -X utf8 this.py"""
import datetime, re
from pathlib import Path

P = Path("D:/\u80be\u810f\u865a\u62df\u7ec6\u80de\u6587\u7ae0\u8bbe\u8ba1")
RV = P / "code" / "R_version"
OUT = Path("D:/claude-code-haha/scripts/_rtrace.txt")
log = []
def w(s=""): log.append(str(s))
def ts(p):
    m = datetime.datetime.fromtimestamp(p.stat().st_mtime).strftime("%Y-%m-%d %H:%M")
    return f"{m}  {p.stat().st_size:>9}"

# 1) recent scripts in R_version (by mtime)
w("==== code/R_version scripts (newest first) ====")
for f in sorted(RV.glob("*"), key=lambda x: x.stat().st_mtime, reverse=True):
    if f.is_file():
        w(f"{ts(f)}  {f.name}")
w("")

# 2) results/qc outputs (R_v1 JSON/CSV)
qc = P / "results" / "qc"
w(f"==== results/qc (exists={qc.exists()}) — R_v1 / moran / spdep outputs ====")
if qc.exists():
    items = sorted(qc.glob("*"), key=lambda x: x.stat().st_mtime, reverse=True)
    for f in items[:40]:
        if f.is_file():
            w(f"{ts(f)}  {f.name}")
w("")

# 3) figures/*Rv1* generated by generate_figures_Rv1.py
w("==== figures/*Rv1* ====")
figs = P / "figures"
if figs.exists():
    for f in sorted(figs.glob("*Rv1*"), key=lambda x: x.stat().st_mtime, reverse=True):
        w(f"{ts(f)}  {f.name}")
w("")

# 4) manuscript/ R-pipeline outputs
w("==== manuscript/ (R6 extracted + FigS4b) ====")
man = P / "manuscript"
for f in sorted(man.glob("*"), key=lambda x: x.stat().st_mtime, reverse=True):
    if f.is_file() and (("R6" in f.name) or ("R5_extracted" in f.name) or ("FigS4b" in f.name) or f.name.startswith("_R")):
        w(f"{ts(f)}  {f.name}")
w("")

# 5) parse output paths hard-coded in the two newest R-chain files
w("==== hard-coded output paths in key scripts ====")
for fn in ("06b_moran_spdep_crosscheck_R.R", "generate_figS4b_moran_spdep_Rv1.py"):
    fp = RV / fn
    if not fp.exists():
        w(f"-- {fn}: MISSING --"); continue
    w(f"-- {fn} --")
    txt = fp.read_text(encoding="utf-8", errors="replace")
    for ln in txt.splitlines():
        if re.search(r"(results/qc|manuscript|\.json|\.csv|\.png|\.pdf|write|savefig|OUT|SRC)", ln) and re.search(r"[\"']", ln):
            s = ln.strip()
            if len(s) < 160 and ("/" in s or "\\" in s or "OUT" in s or "SRC" in s):
                w(f"   {s[:150]}")
    w("")

OUT.write_text("\n".join(log), encoding="utf-8")
print("OK lines=", len(log))
